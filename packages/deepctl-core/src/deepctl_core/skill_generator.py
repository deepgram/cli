# The module-level names are what other packages import and what the test
# suite patches, so they stay. Nothing in this module reads them directly,
# though: the accessors below do, and they follow ``Path.home()`` at call
# time unless a name has been reassigned, so a home that changes after
# import (tests, a wrapper that sets HOME) is honoured either way.
_IMPORT_TIME_SKILLS_DIR = Path.home() / ".deepctl" / "skills"
_SKILLS_DIR = _IMPORT_TIME_SKILLS_DIR
_STATE_FILE = _SKILLS_DIR / "skills.json"
_REPO_CACHE_DIR = _SKILLS_DIR / "repo_cache"

#: How long a deepctl process waits for another one to release
#: ``skills.json`` before giving up with :class:`SkillsStateLockTimeout`.
_STATE_LOCK_TIMEOUT = 30.0


def _skills_dir() -> Path:
    if _SKILLS_DIR != _IMPORT_TIME_SKILLS_DIR:
        return _SKILLS_DIR
    return Path.home() / ".deepctl" / "skills"


def skills_state_file() -> Path:
    """Where ``skills.json``, deepctl's record of what it installed, lives."""
    if _STATE_FILE != _IMPORT_TIME_SKILLS_DIR / "skills.json":
        return _STATE_FILE
    return _skills_dir() / "skills.json"


def _repo_cache_dir() -> Path:
    if _REPO_CACHE_DIR != _IMPORT_TIME_SKILLS_DIR / "repo_cache":
        return _REPO_CACHE_DIR
    return _skills_dir() / "repo_cache"


def _empty_state() -> dict[str, Any]:
    return {"installed_skills": {}, "auto_update": True}


def _parse_state(text: str, path: Path) -> dict[str, Any]:
    try:
        result = json.loads(text)
    except json.JSONDecodeError as exc:
        raise SkillsStateError(
            f"{path} is not valid JSON ({exc}). It records which skill folders "
            "deepctl installed, so deepctl will not guess and start over. Fix "
            "the file, or move it aside and run 'dg skills install' again."
        ) from exc
    if not isinstance(result, dict):
        raise SkillsStateError(
            f"{path} holds a JSON {type(result).__name__}, not an object. It "
            "records which skill folders deepctl installed, so deepctl will not "
            "guess and start over. Fix the file, or move it aside and run "
            "'dg skills install' again."
        )
    return result


def get_skills_state() -> dict[str, Any]:
    """Read the skills state file.

    A missing file is the empty default: nothing has been installed. A
    file that is there but cannot be read as a JSON object raises
    :class:`SkillsStateError` instead, because the one thing worse than
    not knowing what deepctl installed is a later save overwriting the
    record with the claim that it installed nothing.
    """
    path = skills_state_file()
    try:
        text = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        return _empty_state()
    except OSError as exc:
        raise SkillsStateError(
            f"Cannot read {path}: {exc}. Fix its permissions, or move it aside "
            "and run 'dg skills install' again."
        ) from exc
    return _parse_state(text, path)


def save_skills_state(state: dict[str, Any]) -> None:
    """Persist the skills state file atomically.

    Written to a temporary file in the same directory and renamed over
    the old one, so a crash mid-write leaves the previous record intact
    rather than a truncated file. An existing file that does not parse
    is never replaced: that is the record of what deepctl installed, and
    this function raises :class:`SkillsStateError` rather than bury it.
    """
    path = skills_state_file()
    try:
        existing = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        pass
    except OSError as exc:
        raise SkillsStateError(
            f"Cannot read {path} before replacing it: {exc}. Fix its "
            "permissions, or move it aside and run 'dg skills install' again."
        ) from exc
    else:
        _parse_state(existing, path)
    path.parent.mkdir(parents=True, exist_ok=True)
    _atomic_write_text(path, json.dumps(state, indent=2))


def _atomic_write_text(path: Path, text: str, newline: str | None = None) -> None:
    """Replace ``path`` with ``text`` in one rename, never a partial write.

    The caller decides whether ``path`` may be a symlink: a rename
    replaces the link itself, not the file it points at. ``newline`` is
    :func:`open`'s: pass ``""`` to write ``text``'s line endings as they
    are rather than translating them for the platform.
    """
    tmp_name: str | None = None
    try:
        with tempfile.NamedTemporaryFile(
            "w",
            dir=path.parent,
            # One leading dot, so a dotfile's temp copy is not "..name".
            prefix=f".{path.name.lstrip('.')}.",
            suffix=".tmp",
            delete=False,
            encoding="utf-8",
            newline=newline,
        ) as fh:
            tmp_name = fh.name
            fh.write(text)
            fh.flush()
            os.fsync(fh.fileno())
        try:
            shutil.copymode(path, tmp_name)
        except OSError:
            pass
        os.replace(tmp_name, path)
    except BaseException:
        if tmp_name is not None:
            try:
                os.unlink(tmp_name)
            except OSError:
                pass
        raise


# -- the state lock ---------------------------------------------------------
#
# Every route that edits skills.json reads it, changes it and writes it
# back. Two deepctl processes doing that at once -- a login prompt and a
# `dg skills update` in another terminal -- would each save their own
# view and one tool's record would vanish. The lock is a sibling file
# held for the whole read-modify-write; it is re-entrant within a
# process so a caller that already holds it can call into code that
# takes it again.

_state_lock_guard = threading.RLock()
_state_lock_depth = 0
_state_lock_handle: IO[bytes] | None = None


def _lock_file() -> Path:
    state = skills_state_file()
    return state.parent / f"{state.name}.lock"


def _try_lock(fh: IO[bytes]) -> bool:
    """Take the OS-level lock on ``fh`` without waiting; False if held."""
    if sys.platform == "win32":
        import msvcrt

        try:
            fh.seek(0)
            msvcrt.locking(fh.fileno(), msvcrt.LK_NBLCK, 1)
        except OSError:
            return False
        return True
    import fcntl

    try:
        fcntl.flock(fh.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
    except OSError:
        return False
    return True


def _unlock(fh: IO[bytes]) -> None:
    if sys.platform == "win32":
        import msvcrt

        try:
            fh.seek(0)
            msvcrt.locking(fh.fileno(), msvcrt.LK_UNLCK, 1)
        except OSError:
            pass
        return
    import fcntl

    try:
        fcntl.flock(fh.fileno(), fcntl.LOCK_UN)
    except OSError:
        pass


def _acquire_lock_file(deadline: float) -> IO[bytes]:
    lock_path = _lock_file()
    try:
        lock_path.parent.mkdir(parents=True, exist_ok=True)
        # Append mode creates the file without ever truncating it, and
        # never follows a dangling path into creating something else.
        fh: IO[bytes] = open(lock_path, "a+b")  # noqa: SIM115
    except OSError as exc:
        raise SkillsStateError(
            f"Cannot open {lock_path} to lock deepctl's skill records: {exc}"
        ) from exc
    while True:
        if _try_lock(fh):
            return fh
        if time.monotonic() >= deadline:
            fh.close()
            raise SkillsStateLockTimeout(lock_path)
        time.sleep(0.05)


@contextmanager
def skills_state_lock(timeout: float | None = None) -> Iterator[None]:
    """Hold ``skills.json`` against other deepctl processes.

    Wrap every read-modify-write of the state in this. Re-entrant within
    a process; across processes it is ``fcntl.flock`` on POSIX and
    ``msvcrt.locking`` on Windows, on a ``.lock`` file next to the state.

    Raises:
        SkillsStateLockTimeout: The lock was not free within ``timeout``
            seconds (30 by default). A subclass of :class:`SkillsStateError`.
        SkillsStateError: The lock file could not be opened.
    """
    global _state_lock_depth, _state_lock_handle
    if timeout is None:
        timeout = _STATE_LOCK_TIMEOUT
    deadline = time.monotonic() + timeout
    if not _state_lock_guard.acquire(timeout=timeout):
        raise SkillsStateLockTimeout(_lock_file(), holder="thread")
    try:
        if _state_lock_depth == 0:
            _state_lock_handle = _acquire_lock_file(deadline)
        _state_lock_depth += 1
        try:
            yield
        finally:
            _state_lock_depth -= 1
            if _state_lock_depth == 0 and _state_lock_handle is not None:
                _unlock(_state_lock_handle)
                _state_lock_handle.close()
                _state_lock_handle = None
    finally:
        _state_lock_guard.release()


def with_advice(detail: str, advice: str) -> str:
    """``detail`` then ``advice``, with exactly one sentence break between.

    For warnings that put what went wrong in front of what to do about it.
    ``detail`` is often another error's text, which may or may not end in
    a full stop (an ``OSError`` ends in a quoted path), so gluing the two
    by hand gave either ``..`` or no break at all.
    """
    body = detail.rstrip()
    if not body:
        return advice
    if not body.endswith((".", "!", "?")):
        body += "."
    return f"{body} {advice}"


def recorded_skill_paths(state: dict[str, Any], cli_name: str) -> list[str]:
    """Paths ``skills.json`` records deepctl having installed for one tool.

    This is deepctl's only claim of ownership over anything in a tool's
    skills directory. It is a *claim*, not a guarantee — every consumer
    re-checks each path against the tool's skills root before writing to
    it or deleting it, so a stale state file cannot point an operation at
    an unrelated directory. It is not a sandbox against a *hostile* one:
    :meth:`SkillGenerator.owned_skill_paths` lstats only the final
    component, so a hand-written entry whose intermediate component is a
    symlink can still resolve to a direct child of the root and be
    accepted. Anyone who can rewrite ``skills.json`` can already rewrite
    anything else under the same home directory, so that is not a
    boundary worth pretending to hold.

    A user who deletes ``skills.json`` therefore leaves deepctl unable to
    prove it owns anything: install refuses to overwrite the folders it
    previously wrote, and remove deletes nothing. That is the safe
    direction to fail in — the folders are still there to delete by hand.

    Every shape a hand-edited file can hold is tolerated by claiming
    nothing: ``installed_skills`` set to a list or a string, one tool's
    entry set to a null, ``paths`` that is not a list, and a non-string
    inside it all yield an empty result rather than an exception. Callers
    render tables and loops from this, so raising here turns a bad file
    into an error message naming a Python type instead of the file.
    """
    installed = state.get("installed_skills")
    entry = installed.get(cli_name) if isinstance(installed, dict) else None
    if not isinstance(entry, dict):
        return []
    paths = entry.get("paths")
    if not isinstance(paths, list):
        return []
    return [p for p in paths if isinstance(p, str)]


def fetch_repo_skills(
    ref: str | None = None,
    *,
    force: bool = False,
    ref_source: str | None = None,
) -> list[RepoSkill]:
    """Fetch every skill published by deepgram/skills.

    The list comes from the upstream ``.claude-plugin/marketplace.json``
    manifest, never from a list in this repo: upstream CI checks that
    manifest against the directories on disk in both directions on every
    pull request, so it is the one place that cannot drift.

    Args:
        ref: Upstream git ref. Defaults to the pinned release tag.
        force: Re-download even if the ref is already cached.
        ref_source: Where ``ref`` came from, named by a
            :class:`~deepctl_core.skill_bundle.SkillRefNotFoundError`.

    Raises:
        SkillFetchError: The bundle could not be fetched or trusted. This
            is deliberately fatal — see :class:`SkillFetchError`.
    """
    return fetch_skill_bundle(
        ref, cache_dir=_repo_cache_dir(), force=force, ref_source=ref_source
    )


def _commands_hash(commands: list[CommandMetadata]) -> str:
    """Compute a deterministic hash of the command set."""
    blob = json.dumps(
        [
            {
                "name": c.full_command,
                "help": c.help,
                "examples": c.examples,
                "agent_help": c.agent_help,
            }
            for c in sorted(commands, key=lambda c: c.full_command)
        ],
        sort_keys=True,
    )
    return "sha256:" + hashlib.sha256(blob.encode()).hexdigest()[:16]


def skills_need_update(commands: list[CommandMetadata]) -> bool:
    """Return True if the installed skills are stale."""
    state = get_skills_state()
    if not state.get("installed_skills"):
        return False
    new_hash = _commands_hash(commands)
    return any(
        info.get("commands_hash") != new_hash
        for info in state["installed_skills"].values()
    )


