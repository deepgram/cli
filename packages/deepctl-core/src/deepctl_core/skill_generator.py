@dataclass
class SkillInstallReport:
    """What :func:`install_skills_for` did, tool by tool.

    Callers render this; the core never prints. ``conflicts`` is only
    ever non-empty in best-effort mode, and ``failures`` only in
    best-effort or keep-going mode, because otherwise the corresponding
    exception is raised instead.
    """

    #: The deepgram/skills revision that was installed.
    ref: str
    #: The bundle that was fetched, empty when nothing needed fetching.
    skills: list[RepoSkill]
    #: cli_name -> the skill folders written for it, in install order.
    written: dict[str, list[Path]]
    #: Selected tools that have no skills directory to install into.
    unsupported: list[SkillGenerator]
    #: (display_name, destination) pairs deepctl refused to overwrite.
    conflicts: list[tuple[str, Path]]
    #: (display_name, error) for tools that raised part-way through.
    failures: list[tuple[str, Exception]]
    #: cli_name -> retired skill folders that would not delete and are
    #: therefore still recorded as deepctl's, for a later retry.
    stranded: dict[str, list[Path]] = field(default_factory=dict)
    #: cli_name -> retired skill folders deepctl had recorded and deleted
    #: because ``ref`` no longer ships them. Callers tell the user.
    pruned: dict[str, list[Path]] = field(default_factory=dict)
    #: cli_name -> display_name for every tool in :attr:`pruned`, so
    #: :attr:`pruned_notices` can name the tool without a generator.
    pruned_tools: dict[str, str] = field(default_factory=dict)
    #: (display_name, path, reason) for deepctl <= 0.3.0 leftovers found
    #: at a legacy path but left alone, because the content was not
    #: deepctl's or the file could not be edited safely.
    legacy_skipped: list[tuple[str, Path, str]] = field(default_factory=list)
    #: cli_names dropped by ``only_recorded`` because the fresh records no
    #: longer list them -- removed by another deepctl while this one was
    #: downloading. Nothing was written, recorded or pruned for them.
    skipped_unrecorded: list[str] = field(default_factory=list)
    #: (cli_name, display_name) of tools whose record was a remove that
    #: had not finished (see :func:`is_pending_removal`). Only with
    #: ``only_recorded``: nothing was installed for them; the remove was
    #: retried instead, and this one finished it.
    removals_finished: list[tuple[str, str]] = field(default_factory=list)
    #: As :attr:`removals_finished`, for tools whose retried remove still
    #: could not finish. Their records stay, marked, for the next retry.
    removals_pending: list[tuple[str, str]] = field(default_factory=list)

    @property
    def total_written(self) -> int:
        return sum(len(paths) for paths in self.written.values())

    @property
    def pruned_notices(self) -> list[str]:
        """One line per retired skill folder deleted, for callers to print.

        A folder deepctl deletes on its own initiative is said out loud:
        an update that quietly drops a skill reads as data loss.
        """
        return [
            f"Removed retired skill {path.name} from "
            f"{self.pruned_tools.get(cli_name, cli_name)} "
            f"(no longer in deepgram/skills@{self.ref})"
            for cli_name, paths in self.pruned.items()
            for path in paths
        ]


def _ownership_after_failure(
    gen: SkillGenerator,
    skills: list[RepoSkill],
    recorded: Iterable[str | Path],
) -> list[Path]:
    """Every folder of this tool's that deepctl must stay able to touch.

    Used when an install raises part-way: whatever landed at a
    destination the preflight already cleared as ours, plus anything
    previously recorded that is still on disk. Recording less would turn
    a half-written bundle into folders deepctl will neither update nor
    remove, and would later refuse to overwrite.

    Never called for :class:`SkillOwnershipError`, because that is
    raised before the first byte is written and the destinations it
    names are precisely the ones that are *not* deepctl's. A symlink is
    excluded for the same reason: it is never deepctl's, whatever it
    points at, so claiming one would both break that rule and strand the
    record on a path :meth:`SkillGenerator.remove_report` will not follow.
    """
    root = gen.skills_root()
    landed = (
        [
            root / skill.name
            for skill in skills
            if (root / skill.name).exists() and not (root / skill.name).is_symlink()
        ]
        if root is not None
        else []
    )
    surviving = [p for p in gen.owned_skill_paths(recorded) if p.exists()]
    return _unique_paths([*landed, *surviving])


def _surviving_legacy(
    gen: SkillGenerator, recorded: Iterable[str | Path]
) -> list[Path]:
    """The recorded deepctl <= 0.3.0 paths still on disk.

    A partial record keeps them: :meth:`SkillGenerator.install_skills`
    clears those files only once every new folder has landed, so until
    then they are still there and the record has to keep saying so.
    """
    known = {_canonical(p) for p in gen.legacy_locations()}
    kept: list[Path] = []
    for entry in recorded:
        path = Path(entry).expanduser()
        if _canonical(path) in known and (path.exists() or path.is_symlink()):
            kept.append(path)
    return kept


def _unique_paths(paths: Iterable[Path]) -> list[Path]:
    """Sorted, one entry per on-disk location.

    Keyed on :func:`_canonical`, not the spelling: a folder recorded as
    ``/tmp/x`` and landed as ``/private/tmp/x`` is one folder, and
    recording it twice would make ``dg skills list`` count it twice.
    """
    by_key: dict[str, Path] = {}
    for p in paths:
        by_key.setdefault(_canonical(p), p)
    return sorted(by_key.values())


#: Set on a tool's record by a ``dg skills remove`` that could not finish.
#: The record outlives the remove only so a retry can reach what is left;
#: it is not an install, and an update must not treat it as one.
REMOVE_PENDING_KEY = "remove_pending"


def is_pending_removal(entry: Any) -> bool:
    """Whether ``entry`` is a remove that did not finish, not an install.

    A failed ``dg skills remove`` keeps the record so a retry can reach
    what would not go, and marks it with ``remove_pending``. Only that
    marker counts. A record's shape says nothing: deepctl 0.3.0 and 0.3.1
    wrote every install as ``paths`` naming their files, with no
    ``skills`` key, so a record holding only deepctl <= 0.3.0 paths is an
    install waiting to be upgraded, and reading it as a remove had ``dg
    skills update`` delete it and install nothing.
    """
    return isinstance(entry, dict) and entry.get(REMOVE_PENDING_KEY) is True


def mark_pending_removal(
    entry: dict[str, Any], stranded: Iterable[Path], retryable: Iterable[Path]
) -> None:
    """Rewrite a tool's record as a remove that is still to finish."""
    stranded = list(stranded)
    entry["paths"] = [str(p) for p in [*stranded, *retryable]]
    entry["skills"] = [p.name for p in stranded]
    entry[REMOVE_PENDING_KEY] = True


def _finish_pending_removal(
    gen: SkillGenerator, installed: dict[str, Any], report: SkillInstallReport
) -> None:
    """Retry the remove a pending record stands for, instead of installing.

    Drops the record when everything is gone; otherwise keeps it marked,
    holding only what is still on disk, for the next retry.
    """
    entry = installed.get(gen.cli_name)
    recorded = (
        [p for p in entry.get("paths") or [] if isinstance(p, str)]
        if isinstance(entry, dict)
        else []
    )
    removal = gen.remove_report(recorded)
    report.legacy_skipped.extend(
        (gen.display_name, path, reason) for path, reason in removal.legacy_skipped
    )
    if removal.stranded or removal.legacy_retryable:
        if isinstance(entry, dict):
            mark_pending_removal(entry, removal.stranded, removal.legacy_retryable)
        report.removals_pending.append((gen.cli_name, gen.display_name))
    else:
        del installed[gen.cli_name]
        report.removals_finished.append((gen.cli_name, gen.display_name))


def _retire_unsupported(
    unsupported: Iterable[SkillGenerator],
    installed: dict[str, Any],
    report: SkillInstallReport | None = None,
) -> bool:
    """Clean up after tools deepctl cannot install to, and un-record them.

    Nothing was written for them, so nothing may claim it was: an entry
    here would make ``dg skills list`` show a tool as installed with no
    skills, and ``dg skills update`` chase it every run.

    A legacy file found but left alone -- the user's own content at a
    path deepctl <= 0.3.0 wrote -- goes into ``report.legacy_skipped``
    when a report is given, so the caller can name it instead of the
    hint silently repeating on every run.

    Returns:
        True when a record was dropped, so the caller knows to save.
    """
    changed = False
    for gen in unsupported:
        try:
            legacy = gen.clean_legacy_report()
        except OSError:
            # Best-effort: these are deepctl <= 0.3.0 leftovers for a tool
            # nothing is being installed to. An unreadable ~/.gemini/GEMINI.md
            # must not abort an install that is about to write real skill
            # folders for every other tool.
            pass
        else:
            if report is not None:
                report.legacy_skipped.extend(
                    (gen.display_name, path, reason) for path, reason in legacy.skipped
                )
        # `in` rather than the return of pop(): a hand-edited skills.json
        # can hold a null for a tool, and popping that would look like
        # nothing was dropped and leave the record unsaved.
        if gen.cli_name in installed:
            del installed[gen.cli_name]
            changed = True
    return changed


def install_skills_for(
    generators: Sequence[SkillGenerator],
    state: dict[str, Any],
    *,
    commands: list[CommandMetadata],
    version: str,
    ref: str | None = None,
    fetch: Callable[[], list[RepoSkill]] | None = None,
    on_installed: Callable[[SkillGenerator, list[Path]], None] | None = None,
    best_effort: bool = False,
    keep_going: bool = False,
    load_state: Callable[[], dict[str, Any]] | None = None,
    only_recorded: bool = False,
) -> SkillInstallReport:
    """Install the upstream skills for several tools under one contract.

    Every route that writes skill folders goes through here -- ``dg
    skills install`` and ``update``, the post-login prompt, and the
    refresh a plugin change triggers -- so they cannot drift apart on the
    one thing that matters: a folder on disk always has an ownership
    record.

    The contract is:

    * **Fetch once, before the lock.** One bundle for every tool, so two
      destinations cannot end up holding different revisions; and fetched
      before ``skills.json`` is locked, so a slow download never makes a
      second deepctl process time out waiting. No skill folder is
      written when the fetch fails; with ``only_recorded``, a remove
      left pending is finished (and saved) first. The "before the lock" half only holds when the
      caller passes ``load_state`` and does not hold
      :func:`skills_state_lock` itself. Without ``load_state`` a caller
      that wants current records has to hold the lock across its own
      read, and the lock is re-entrant, so it stays held through the
      download.
    * **Read the state under the lock.** With ``load_state``, the records
      are re-read once the lock is taken and replace the contents of
      ``state`` in place, so a record another deepctl process saved while
      this one was downloading is kept rather than overwritten by a
      stale view.
    * **Preflight every destination first.** A collision in the last tool
      stops the first from being written at all, rather than leaving a
      half-applied update.
    * **Save after each tool.** If a later one fails, the folders already
      written stay deepctl's to update and remove.
    * **Record what landed even on failure**, so a tool that raises
      part-way still owns the folders that exist. A partial record keeps
      the previously recorded ``skills_ref`` and ``version`` (or carries
      none), so a half-updated tool never reads as current to ``update``.
    * **Prune retired skills after recording**, never before: a crash in
      between should leave a stale folder, not an untracked one.

    ``state`` is mutated and saved in place.

    Args:
        generators: The tools to install for. Ones with no skills
            directory are reported in ``unsupported`` and never recorded.
        state: The loaded ``skills.json``. With ``load_state`` its
            contents are replaced (``clear`` then ``update``) by a fresh
            read under the lock, so the caller's reference sees the
            records this call saved.
        commands: Command metadata, for the recorded ``commands_hash``.
        version: The deepctl version to record.
        ref: The deepgram/skills revision, or ``None`` for the default.
        fetch: Overrides how the bundle is obtained, for a caller that
            reports a download failure in its own words. Called at most
            once, and only when there is something to install.
        on_installed: Called with each tool and its folders as that tool
            lands, so a caller can report it before a later tool fails.
        best_effort: Collect conflicts and errors into the report and
            keep going instead of raising, for callers such as login that
            must not fail the command they are attached to.
        keep_going: Report a tool whose skills directory cannot be
            written (a :class:`SkillWriteError`) in ``failures`` and go
            on to the next tool, instead of raising. Any other error
            still raises. Unlike ``best_effort``, a conflict is still
            raised before anything is written. For ``dg skills update``
            and the multi-tool installs, which try every tool and then
            fail the command if any of them failed.
        load_state: Reads ``skills.json`` afresh. When given, the bundle
            is fetched and its manifest read with no lock held, then the
            lock is taken and this is called before anything else runs.
            Whatever it raises -- a caller refusing unreadable records,
            say -- propagates unchanged, and nothing is written. ``None``
            trusts ``state`` as passed.
        only_recorded: For an update. With ``load_state``, every tool
            whose ``cli_name`` the fresh records do not list is dropped
            before the preflight and named in
            :attr:`SkillInstallReport.skipped_unrecorded`: a ``dg skills
            remove`` that landed while this call was downloading must not
            be undone by it. When that drops every tool, the report is
            empty, not a failure, and nothing is written. Ignored without
            ``load_state``, since ``state`` is then the caller's own view.

    Returns:
        A :class:`SkillInstallReport` for the caller to render.

    Raises:
        SkillFetchError: Upstream could not be fetched or trusted. Raised
            in both modes, because no skill folder has been written yet.
            With ``only_recorded``, a remove left pending may already be
            finished and saved: this and every other exception raised
            after one finished carries it, for
            :func:`removals_finished_by` to read.
        SkillWriteError: A tool's skills directory could not be written
            to. Names the directory, not the staging folder inside it.
            Reported in ``failures`` instead when ``best_effort`` or
            ``keep_going`` is set.
        SkillOwnershipError: A destination exists that deepctl did not
            install. Not raised when ``best_effort`` is set.
        SkillsStateLockTimeout: ``skills.json`` is held by another
            deepctl process.
        SkillsStateError: ``skills.json`` cannot be read or written safely.
        Exception: Whatever ``load_state`` raises, unchanged.
    """
    from deepctl_core.skill_bundle import resolve_skills_ref

    supported, unsupported = installable_generators(list(generators))
    report = SkillInstallReport(
        ref=resolve_skills_ref(ref),
        skills=[],
        written={},
        unsupported=unsupported,
        conflicts=[],
        failures=[],
    )
    try:
        return _install_skills_into(
            report,
            supported,
            unsupported,
            state,
            commands=commands,
            version=version,
            ref=ref,
            fetch=fetch,
            on_installed=on_installed,
            best_effort=best_effort,
            keep_going=keep_going,
            load_state=load_state,
            only_recorded=only_recorded,
        )
    except Exception as exc:
        # A remove finished before the failure is done and saved; the
        # report that would have said so never reaches the caller.
        if report.removals_finished and not removals_finished_by(exc):
            exc.removals_finished = list(  # type: ignore[attr-defined]
                report.removals_finished
            )
        raise


def removals_finished_by(exc: BaseException) -> list[tuple[str, str]]:
    """The pending removes an :func:`install_skills_for` call finished
    before raising ``exc``, as (cli_name, display_name) pairs.

    Those removes are done and saved whatever went wrong after them, so
    a caller says so before reporting the error. Empty for any other
    exception.
    """
    found = getattr(exc, "removals_finished", None)
    return list(found) if isinstance(found, list) else []


def _install_skills_into(
    report: SkillInstallReport,
    supported: list[SkillGenerator],
    unsupported: list[SkillGenerator],
    state: dict[str, Any],
    *,
    commands: list[CommandMetadata],
    version: str,
    ref: str | None,
    fetch: Callable[[], list[RepoSkill]] | None,
    on_installed: Callable[[SkillGenerator, list[Path]], None] | None,
    best_effort: bool,
    keep_going: bool,
    load_state: Callable[[], dict[str, Any]] | None,
    only_recorded: bool,
) -> SkillInstallReport:
    """:func:`install_skills_for` after ``report`` is built; see there."""
    from datetime import datetime, timezone

    def installed_records() -> dict[str, Any]:
        """``state["installed_skills"]``, made a dict if it is not one."""
        if load_state is not None:
            # Taken under the lock: the records another process saved
            # while this one was fetching replace the caller's view.
            fresh = load_state()
            state.clear()
            state.update(fresh)
        # Not setdefault: a hand-edited skills.json can carry a null or a
        # list here, and every write below would then raise instead of
        # installing. recorded_skill_paths() tolerates the same damage.
        found = state.get("installed_skills")
        if not isinstance(found, dict):
            found = {}
            state["installed_skills"] = found
        return found

    def drop_unrecorded(installed: dict[str, Any]) -> bool:
        """Apply ``only_recorded``; True when no tool is left to touch."""
        nonlocal supported, unsupported
        if not only_recorded or load_state is None:
            return False
        # Extended, not assigned: this runs before the fetch and again
        # after it, and the second pass only sees what the first kept.
        report.skipped_unrecorded.extend(
            g.cli_name
            for g in [*supported, *unsupported]
            if g.cli_name not in installed
        )
        supported = [g for g in supported if g.cli_name in installed]
        unsupported = [g for g in unsupported if g.cli_name in installed]
        # A remove that did not finish is retried, never reinstalled over.
        pending = [
            g
            for g in [*supported, *unsupported]
            if is_pending_removal(installed.get(g.cli_name))
        ]
        if pending:
            for gen in pending:
                _finish_pending_removal(gen, installed, report)
            save_skills_state(state)
            supported = [g for g in supported if g not in pending]
            unsupported = [g for g in unsupported if g not in pending]
        report.unsupported = unsupported
        if supported or unsupported:
            return False
        report.skills = []
        return True

    if not supported:
        # Nothing to install means nothing to download.
        with skills_state_lock():
            installed = installed_records()
            if drop_unrecorded(installed):
                return report
            if _retire_unsupported(unsupported, installed, report):
                save_skills_state(state)
        return report

    if only_recorded and load_state is not None:
        # Settled before the download: a record that is a remove still to
        # finish is retried rather than installed over, and when every
        # recorded tool is one there is nothing to fetch at all.
        with skills_state_lock():
            if drop_unrecorded(installed_records()):
                return report
        if not supported:
            with skills_state_lock():
                installed = installed_records()
                if drop_unrecorded(installed):
                    return report
                if _retire_unsupported(unsupported, installed, report):
                    save_skills_state(state)
            return report

    # Fetched before the lock, deliberately: a download can take as long
    # as the network allows, and a second deepctl waiting on skills.json
    # meanwhile would time out for nothing. Bundle publication is atomic
    # on its own, and the fetch writes nothing under any tool's root, so
    # a failure here installs nothing. Only a pending remove settled
    # above has changed anything, and install_skills_for says so.
    skills = fetch() if fetch is not None else fetch_repo_skills(ref, force=True)
    report.skills = skills

    # One lock around state read, preflight, writes and saves: another
    # deepctl process reading skills.json meanwhile would otherwise save
    # its own view over the records written here.
    with skills_state_lock():
        installed = installed_records()
        # A tool removed while the bundle downloaded stays removed: the
        # caller's list predates that remove, the fresh records do not.
        if drop_unrecorded(installed):
            return report
        targets: list[SkillGenerator] = []
        for gen in supported:
            found = gen.install_conflicts(
                skills, recorded_skill_paths(state, gen.cli_name)
            )
            if found:
                report.conflicts.extend((gen.display_name, p) for p in found)
            else:
                targets.append(gen)
        if report.conflicts and not best_effort:
            raise SkillOwnershipError(report.conflicts)

        # After the fetch and the preflight, so a download failure or a
        # collision leaves these tools' files alone -- but before the
        # writes, so a tool failing part-way through the loop cannot
        # skip it and leave a stale record behind.
        if _retire_unsupported(unsupported, installed, report):
            save_skills_state(state)

        commands_hash = _commands_hash(commands)
        now = datetime.now(timezone.utc).isoformat()

        #: The record fields that say "this tool holds revision X of
        #: deepctl Y". Stamped only once every requested skill has landed.
        _STAMP = ("installed_at", "version", "commands_hash", "skills_ref")

        def record(
            gen: SkillGenerator,
            paths: Iterable[Path],
            *,
            complete: bool,
            previous: dict[str, Any] | None = None,
        ) -> None:
            """Save ``paths`` as this tool's folders.

            ``complete`` stamps the new ref and version. A partial record
            -- written skill by skill as the bundle lands, or after a
            failure -- carries the previously recorded stamp instead, or
            none for a first install: some folders still hold the old
            release, so claiming the new ref would make a bare ``dg
            skills update`` treat a half-updated tool as current.

            A partial record over a remove that had not finished stays
            marked as one until the install completes. Otherwise a failed
            install would turn the folders that remove left behind back
            into an install, with the old stamp, which ``list`` showed as
            current and ``status`` (which looks at the disk) did not.
            """
            kept = _unique_paths(paths)
            # ``skills`` names the folders directly under the skills root
            # only. A partial record also keeps the deepctl <= 0.3.0 files
            # still on disk, so a later run can clear them, but those are
            # not skills: listing ``deepctl.mdc`` as one made ``list``
            # count it.
            root = gen.skills_root()
            home = None if root is None else _canonical(root.expanduser())
            entry: dict[str, Any] = {
                "paths": [str(p) for p in kept],
                "skills": [p.name for p in kept if _canonical(p.parent) == home],
            }
            if complete:
                entry.update(
                    installed_at=now,
                    version=version,
                    commands_hash=commands_hash,
                    skills_ref=report.ref,
                )
            elif previous is not None:
                entry.update({k: previous[k] for k in _STAMP if k in previous})
                if is_pending_removal(previous):
                    entry[REMOVE_PENDING_KEY] = True
            installed[gen.cli_name] = entry
            save_skills_state(state)

        for gen in targets:
            recorded = recorded_skill_paths(state, gen.cli_name)
            landed: list[Path] = []
            # What skills.json said about this tool before this install
            # touched it; the stamp partial records carry forward.
            was = installed.get(gen.cli_name)
            previous: dict[str, Any] | None = was if isinstance(was, dict) else None

            def on_landed(
                dest: Path,
                gen: SkillGenerator = gen,
                recorded: list[str] = recorded,
                landed: list[Path] = landed,
                previous: dict[str, Any] | None = previous,
            ) -> None:
                # Record the folder the moment its rename lands, before
                # the next skill is copied: an interrupt between the two
                # then leaves a recorded folder, not an orphan. Earlier
                # recorded folders not replaced yet are still deepctl's
                # previous content, so they stay in the record too -- and
                # so the record keeps the previous ref, not the new one.
                landed.append(dest)
                surviving = (p for p in gen.owned_skill_paths(recorded) if p.exists())
                record(
                    gen,
                    [*landed, *surviving, *_surviving_legacy(gen, recorded)],
                    complete=False,
                    previous=previous,
                )

            token = _ON_SKILL_LANDED.set(on_landed)
            try:
                paths = gen.install_skills(skills, recorded)
            except BaseException as exc:
                # A collision is raised before anything is written, and
                # the destinations it names are the ones that are NOT
                # deepctl's. Claiming them here would convert a refusal
                # to touch someone else's folder into a record saying it
                # is ours, which the next install would then delete.
                #
                # BaseException, not Exception: a Ctrl-C mid-install is
                # exactly the case where a folder landed and the record
                # has to say so before the process goes away.
                # The deepctl <= 0.3.0 files are cleared only after every
                # folder lands, so on a failure they are all still there,
                # and so is the record naming them.
                kept = (
                    []
                    if isinstance(exc, SkillOwnershipError)
                    else _ownership_after_failure(gen, skills, recorded)
                )
                if kept:
                    kept = [*kept, *_surviving_legacy(gen, recorded)]
                if kept:
                    record(gen, kept, complete=False, previous=previous)
                if not isinstance(exc, Exception):
                    raise
                # The raw OSError named a staging folder inside the root;
                # the user needs the root.
                failure = _as_write_error(gen, exc)
                # keep_going covers a skills directory that cannot be
                # written, which is that tool's alone. Anything else -- a
                # bundle cache that will not read, a bug -- would fail the
                # next tool the same way, so it still stops the run.
                if not (
                    best_effort or (keep_going and isinstance(failure, SkillWriteError))
                ):
                    if failure is exc:
                        raise
                    raise failure from exc
                report.failures.append((gen.display_name, failure))
                continue
            finally:
                _ON_SKILL_LANDED.reset(token)

            # install_skills() has cleared the deepctl <= 0.3.0 files now
            # that every folder landed; this pass (idempotent) names the
            # ones it left alone.
            legacy = gen.clean_legacy_report()
            report.legacy_skipped.extend(
                (gen.display_name, path, reason) for path, reason in legacy.skipped
            )

            installed[gen.cli_name] = {
                "paths": [str(p) for p in paths],
                "installed_at": now,
                "version": version,
                "commands_hash": commands_hash,
                "skills_ref": report.ref,
                "skills": [s.name for s in skills],
            }
            # Record each tool as it lands. If the next one raises -- a
            # read-only mount, a full disk -- the folders already written
            # stay deepctl's to update and remove, instead of becoming
            # unowned litter it will later refuse to touch.
            save_skills_state(state)
            pruned = gen.prune_retired_result(recorded, skills)
            if pruned.pruned:
                report.pruned[gen.cli_name] = pruned.pruned
                report.pruned_tools[gen.cli_name] = gen.display_name
            # A retired folder that would not delete stays recorded, the
            # same way remove_report() keeps a folder it could not delete: the
            # record is what lets the next update or remove try again.
            stranded = pruned.stranded
            if stranded:
                report.stranded[gen.cli_name] = stranded
                record(gen, [*paths, *stranded], complete=True)
            report.written[gen.cli_name] = paths
            # Report each tool as it lands, not once the loop is over: a
            # later tool raising must not hide the ones that did install
            # and are now recorded.
            if on_installed is not None:
                on_installed(gen, paths)

    return report
