"""Install Deepgram skills into AI coding assistants.

What gets installed depends on whether the target tool has a skills
directory:

* A tool that loads skill *folders* gets the **Deepgram skills**
  themselves, fetched from deepgram/skills by
  :mod:`deepctl_core.skill_bundle`. A skill is a folder (``SKILL.md``
  plus, for some, a ``references/`` subdirectory), and it is installed
  verbatim into the directory that tool loads skills from.
* A tool with no skills directory gets nothing written.
  :meth:`SkillGenerator.manual_hint` points the user at
  ``npx skills add deepgram/skills`` instead. The only thing deepctl does
  to such a tool's files is clean up what deepctl 0.3.1 and earlier wrote
  there, and only where the file still carries the header deepctl wrote.

Writing skills anywhere else is what produced
``~/.claude/commands/deepgram/api.md`` (the slash-command directory,
holding a skill) and a 58 KB ``instructions.md`` with four skills
concatenated inside a marker that claimed to be a CLI reference.
"""

