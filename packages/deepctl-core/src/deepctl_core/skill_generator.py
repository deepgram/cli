class SkillsStateError(Exception):
    """``skills.json`` cannot be read, written or locked safely.

    Raised instead of quietly starting over: a state file that exists but
    does not parse still describes folders deepctl installed, and a save
    on top of an empty default would turn every one of them into litter
    deepctl will neither update nor remove. The message names the file
    and what to do about it.
    """


class SkillsStateLockTimeout(SkillsStateError):
    """Another deepctl process held the records lock for the whole wait.

    Raised only on timeout, never for a lock file that could not be
    opened, so a caller can tell "try again in a moment" from "fix the
    file". The lock is ``flock``/``msvcrt.locking``, which the OS drops
    the moment its holder exits, so the message never tells the user to
    delete the lock file: a stale one cannot exist, and a deleted one
    would let two live processes write ``skills.json`` over each other.
    """

    def __init__(self, lock_path: Path, holder: str = "process") -> None:
        self.lock_path = lock_path
        self.holder = holder
        super().__init__(
            f"Another deepctl {holder} holds the skill records lock at "
            f"{lock_path}. Wait for it to finish and retry; the lock is "
            "released automatically when that process exits."
        )

    def __reduce__(self) -> tuple[Any, ...]:
        # BaseException rebuilds from ``self.args`` (the message alone).
        # The third item restores ``__dict__``: add_note() notes and any
        # attribute set later.
        return (type(self), (self.lock_path, self.holder), self.__dict__)


class SkillOwnershipError(Exception):
    """A destination already exists and deepctl did not put it there.

    Every tool deepctl installs into reads a *shared* skills directory —
    ``~/.claude/skills`` and friends hold skills from the user and from
    other publishers too. deepctl therefore only ever replaces or deletes
    a folder it recorded installing itself, and raises this instead of
    touching anything else.
    """

    def __init__(self, conflicts: Sequence[tuple[str, Path]]) -> None:
        self.conflicts = list(conflicts)
        listing = "\n".join(f"  {name}: {path}" for name, path in self.conflicts)
        super().__init__(
            "Refusing to overwrite skills deepctl did not install:\n"
            f"{listing}\n\n"
            f"Either {_STATE_FILE} has no record of deepctl installing "
            "them, so they belong to you or to another publisher, or the "
            "path is now a symlink, which deepctl never writes through. "
            "Rename or delete them and run the install again. Nothing "
            "was installed."
        )

    def __reduce__(self) -> tuple[Any, ...]:
        # BaseException rebuilds from ``self.args`` (the message alone).
        # The third item restores ``__dict__``: add_note() notes and any
        # attribute set later.
        return (type(self), (self.conflicts,), self.__dict__)


#: errnos where the fix is the folder's permissions, not the disk.
_PERMISSION_ERRNOS = frozenset({errno.EACCES, errno.EPERM, errno.EROFS})


class SkillWriteError(Exception):
    """A tool's skills directory could not be written to.

    Raised (or, with ``best_effort``, reported) in place of the
    ``OSError`` behind it, which named a staging folder such as
    ``.speech-to-text.tmp-1447``: a path the user never chose and cannot
    act on. This names the skills directory itself.
    """

    def __init__(self, root: Path, strerror: str, errno_: int | None = None) -> None:
        self.root = root
        self.strerror = strerror
        self.errno = errno_
        super().__init__(f"could not write to {root}: {strerror}.")

    def advice(self, command: str | None = None) -> str:
        """What to do about it; ``command`` names the command to run again."""
        # Permissions only when the errno says so: a full disk or an I/O
        # error, or one whose errno is unknown, told to fix permissions
        # sends the user after the wrong problem.
        fix = "Fix its permissions" if self.errno in _PERMISSION_ERRNOS else "Fix that"
        again = f"run '{command}' again" if command else "run the command again"
        return f"{fix} and {again}."

    def __reduce__(self) -> tuple[Any, ...]:
        return (type(self), (self.root, self.strerror, self.errno), self.__dict__)


#: ``str(OSError)`` as :func:`shutil.copytree` stores it in a
#: :class:`shutil.Error` entry: ``[Errno 28] No space left on device:
#: '/path'``. Windows writes ``[WinError 5]``, whose number is not an errno.
_OSERROR_TEXT = re.compile(
    r"\[(?P<kind>Errno|WinError) (?P<num>-?\d+)\] (?P<strerror>.*?)"
    r"(?:: (?P<filename>'.*'|\".*\"))?$",
    re.DOTALL,
)

#: The Windows error numbers whose advice differs, as the errno they mean:
#: ERROR_ACCESS_DENIED and ERROR_DISK_FULL.
_WINERROR_ERRNOS = {5: errno.EACCES, 112: errno.ENOSPC}


def _first_copy_failure(exc: shutil.Error) -> OSError | None:
    """The first per-file failure ``copytree`` folded into ``exc``, as an OSError.

    :func:`shutil.copytree` keeps copying past a failed file and raises
    one :class:`shutil.Error` at the end, whose ``args[0]`` is a list of
    ``(src, dst, str(why))``. That error has no errno, filename or
    strerror of its own, so it is judged by its first entry instead.
    ``None`` when the entry is not in that shape.
    """
    import ast

    entries = exc.args[0] if exc.args else None
    if not isinstance(entries, list) or not entries:
        return None
    first = entries[0]
    if not (isinstance(first, tuple) and len(first) == 3):
        return None
    _src, dst, why = first
    if isinstance(why, OSError):
        return why
    match = _OSERROR_TEXT.match(str(why))
    if match is None:
        return OSError(None, str(why), os.fsdecode(dst))
    filename: str = os.fsdecode(dst)
    if match["filename"]:
        try:
            parsed = ast.literal_eval(match["filename"])
        except (SyntaxError, ValueError):
            parsed = None
        if isinstance(parsed, str):
            filename = parsed
    number = int(match["num"])
    code = number if match["kind"] == "Errno" else _WINERROR_ERRNOS.get(number)
    return OSError(code, match["strerror"], filename)


def _as_write_error(gen: SkillGenerator, exc: Exception) -> Exception:
    """``exc`` as a :class:`SkillWriteError` naming ``gen``'s skills root.

    Only an ``OSError`` about the root or something under it (or one of
    the root's own parents, when the root could not be created) is
    translated. A :class:`shutil.Error` is judged by the first file it
    failed on (see :func:`_first_copy_failure`), so a failure reading the
    bundle cache under ``~/.deepctl`` is not reported as the skills
    directory's. Anything else comes back unchanged.
    """
    root = gen.skills_root()
    if not isinstance(exc, OSError) or root is None:
        return exc
    cause: OSError | None = exc
    if isinstance(exc, shutil.Error):
        cause = _first_copy_failure(exc)
    if cause is None:
        return exc
    if cause.filename is not None:
        try:
            where = Path(os.fsdecode(cause.filename)).resolve()
            base = root.resolve()
            cache = _repo_cache_dir().resolve()
        except (OSError, TypeError, ValueError):
            return exc
        if where == cache or cache in where.parents:
            return exc
        if not (where == base or base in where.parents or where in base.parents):
            return exc
    return SkillWriteError(root, cause.strerror or str(cause), cause.errno)


