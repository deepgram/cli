# -- path identity ----------------------------------------------------------

#: Module-level so a test can stand in for a case-folding platform.
_normcase = os.path.normcase


def _canonical(path: Path) -> str:
    """One string per on-disk location, as far as the OS lets us tell.

    ``resolve()`` follows symlinks and collapses ``..``; ``normcase``
    folds case where the platform's filesystems do. Two spellings of one
    folder must compare equal here, or a record written as ``API`` would
    make an install of ``api`` look like someone else's folder.
    """
    return _normcase(str(path.resolve()))


def _same_location(a: Path, b: Path) -> bool:
    if _canonical(a) == _canonical(b):
        return True
    # normcase is the identity on POSIX, yet macOS volumes fold case by
    # default. When both paths exist the filesystem itself can answer.
    try:
        return os.path.samefile(a, b)
    except OSError:
        return False


# -- replacing a skill folder -----------------------------------------------


def _remove_path(path: Path) -> None:
    """Best-effort removal of a file, symlink or tree; never raises."""
    try:
        if path.is_symlink() or path.is_file():
            path.unlink()
        elif path.is_dir():
            shutil.rmtree(path, ignore_errors=True)
    except OSError:
        pass


def _staging_sibling(dest: Path) -> Path:
    return dest.parent / f".{dest.name}.tmp-{os.getpid()}"


def _unique_sibling(dest: Path, kind: str) -> Path:
    n = 0
    while True:
        candidate = dest.parent / f".{dest.name}.{kind}-{os.getpid()}-{n}"
        if not candidate.exists() and not candidate.is_symlink():
            return candidate
        n += 1


def _sweep_stale_siblings(dest: Path) -> None:
    """Drop leftovers of an earlier, interrupted replacement of ``dest``.

    Only names this module itself generates -- ``.<skill>.tmp-<pid>`` and
    ``.<skill>.old-<pid>-<n>`` -- and never through a symlink. They are
    hidden, so no tool loads them, but they are also unrecorded, and the
    rule is that nothing unrecorded of deepctl's stays on disk.

    The match is exact, not a prefix: :func:`_staging_sibling` writes
    ``.<skill>.tmp-<pid>`` and :func:`_unique_sibling` writes
    ``.<skill>.old-<pid>-<n>``, both all-digit suffixes, so a user's
    ``.api.old-backup`` or ``.api.tmp-notes`` is not deepctl's and stays.
    """
    pattern = re.compile(rf"\.{re.escape(dest.name)}\.(tmp-\d+|old-\d+-\d+)")
    try:
        names = os.listdir(dest.parent)
    except OSError:
        return
    for name in names:
        if pattern.fullmatch(name):
            leftover = dest.parent / name
            if not leftover.is_symlink():
                _remove_path(leftover)


def _replace_skill_folder(src: Path, dest: Path) -> None:
    """Put a copy of ``src`` at ``dest`` without ``dest`` ever being half-written.

    The copy goes to a staging sibling first; whatever was at ``dest``
    is moved aside; the staging copy is renamed into place; the old copy
    is deleted. A failure or ``KeyboardInterrupt`` anywhere in that
    sequence removes the staging copy and, if the final rename never
    happened, puts the old folder back -- so ``dest`` is either the
    previous content or the new content, and the caller records
    ownership the moment this returns.
    """
    staging = _staging_sibling(dest)
    _sweep_stale_siblings(dest)
    displaced: Path | None = None
    landed = False
    try:
        shutil.copytree(src, staging)
        if dest.exists() or dest.is_symlink():
            displaced = _unique_sibling(dest, "old")
            os.replace(dest, displaced)
        os.replace(staging, dest)
        landed = True
    except BaseException:
        _remove_path(staging)
        if displaced is not None and not landed:
            try:
                os.replace(displaced, dest)
            except OSError:
                pass
        raise
    if displaced is not None:
        _remove_path(displaced)


