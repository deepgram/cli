class AiderGenerator(SkillGenerator):
    """Aider — no skills mechanism; it reads whole files listed in config."""

    cli_name = "aider"
    display_name = "Aider"

    _LEGACY_FILE = Path.home() / ".deepctl" / "skills" / "deepctl-conventions.md"

    def detect(self) -> bool:
        return shutil.which("aider") is not None

    def legacy_paths(self) -> list[LegacyArtifact]:
        return [LegacyArtifact(self._LEGACY_FILE)]

    def clean_legacy_report(self) -> LegacyCleanupReport:
        report = super().clean_legacy_report()
        conf_path = self._config_path()
        changed, reason = self._drop_config_ref()
        if changed:
            report.removed.append(conf_path)
        elif reason is not None:
            report.skip([(conf_path, reason)])
        return report

    def legacy_locations(self) -> list[Path]:
        # deepctl <= 0.3.0 never recorded the config, but a retried
        # remove keeps it on the record (see clean_legacy_report).
        return [*super().legacy_locations(), self._config_path()]

    @staticmethod
    def _config_path() -> Path:
        return Path.home() / ".aider.conf.yml"

    def _drop_config_ref(self) -> tuple[bool, str | None]:
        """Drop the stale ``read:`` entry from ``~/.aider.conf.yml``.

        A textual edit, not a YAML round-trip: ``yaml.dump`` of a parsed
        file throws away the user's comments, key order and quoting, and
        this is their config, not deepctl's. Only the entry naming the
        legacy conventions file is removed, whether the ``read:`` key
        holds a block list, a flow list or a single scalar, and every
        other byte -- line endings included -- comes back as it was.

        Returns ``(changed, reason)``: ``reason`` is set when the file
        names the entry but was not edited -- it is a symlink, could not
        be read or written, or holds a ``read:`` list too irregular to
        edit safely -- so the caller can say so instead of the entry
        silently surviving.
        """
        conf_path = self._config_path()
        entry = str(self._LEGACY_FILE)
        by_hand = f"remove the {entry} entry by hand."
        refs = {entry, str(self._LEGACY_FILE.resolve())}
        try:
            under_home = self._LEGACY_FILE.relative_to(Path.home())
            refs.update({"~/" + str(under_home), "~/" + under_home.as_posix()})
        except ValueError:
            pass

        def names_entry() -> bool:
            """Whether the raw bytes mention the entry, in any spelling.

            For a file deepctl will not edit as text. Warning about one
            that never named the entry repeated a false alarm on every
            run, with advice to remove something that is not there.
            """
            try:
                data = conf_path.read_bytes()
            except OSError:
                # Unreadable through the link: it may name the entry.
                return True
            return any(ref.encode("utf-8") in data for ref in refs)

        if conf_path.is_symlink():
            if not names_entry():
                return False, None
            return False, f"is a symlink, which deepctl never writes through; {by_hand}"
        if not conf_path.exists():
            return False, None
        try:
            # newline="" so a CRLF file is read, and written back, as CRLF.
            with conf_path.open("r", encoding="utf-8", newline="") as fh:
                text = fh.read()
        except OSError as exc:
            return False, _could_not("read", exc, f"Fix its permissions, or {by_hand}")
        except UnicodeDecodeError:
            if not names_entry():
                return False, None
            return False, f"is not UTF-8 text, so deepctl will not edit it; {by_hand}"
        new_text, changed, problem = _drop_yaml_read_entry(text, refs)
        if problem is not None:
            return False, f"{problem}; {by_hand}"
        if not changed:
            return False, None
        # The rename below would replace a read-only file anyway. A
        # read-only GEMINI.md is left alone, so this one is too.
        if not os.access(conf_path, os.W_OK):
            denied = PermissionError(errno.EACCES, os.strerror(errno.EACCES))
            return False, _could_not(
                "edited", denied, f"Fix its permissions, or {by_hand}"
            )
        try:
            _atomic_write_text(conf_path, new_text, newline="")
        except OSError as exc:
            # The error names the temporary file; the user needs the config.
            return False, _could_not(
                "rewritten",
                exc,
                "deepctl replaces the file in one step, which needs write "
                f"permission on its folder. Fix that, or {by_hand}",
            )
        return True, None


def _yaml_scalar(raw: str) -> str:
    """The value of a YAML scalar as written on one line, unquoted."""
    value = raw.strip()
    if value[:1] in ("'", '"') and value[-1:] == value[:1] and len(value) >= 2:
        return value[1:-1]
    # An unquoted scalar ends where a ` #` comment begins.
    return value.split(" #", 1)[0].rstrip()


def _split_yaml_comment(tail: str) -> tuple[str, str]:
    """``tail`` split into its value and its trailing ``# comment``.

    The comment keeps the whitespace in front of it, so joining the two
    gives back ``tail`` exactly. A ``#`` only starts a comment outside
    quotes and at the start or after whitespace, as in YAML.
    """
    quote = ""
    for i, ch in enumerate(tail):
        if quote:
            if ch == quote:
                quote = ""
        elif ch in ("'", '"'):
            quote = ch
        elif ch == "#" and (i == 0 or tail[i - 1] in " \t"):
            start = i
            while start and tail[start - 1] in " \t":
                start -= 1
            return tail[:start], tail[start:]
    return tail, ""


def _drop_flow_entries(
    value: str, names_ref: Callable[[str], bool]
) -> tuple[str, int, int] | None:
    """``value`` (a one-line ``[a, b]``) without the entries naming a ref.

    Returns the new value, how many entries were dropped and how many
    are left, with the user's spacing kept around everything that stays.
    ``None`` means the list is not one this can edit safely: nested,
    quoted around a comma, or not closed on this line.
    """
    lead = value[: len(value) - len(value.lstrip())]
    flow = value.strip()
    if not (flow.startswith("[") and flow.endswith("]")):
        return None
    inner = flow[1:-1]
    if not inner.strip():
        return value, 0, 0
    if any(ch in inner for ch in "[]{}#"):
        return None
    segments = inner.split(",")
    for segment in segments:
        item = segment.strip()
        if not item:
            return None
        if item[0] in ("'", '"'):
            if len(item) < 2 or item[-1] != item[0] or item[0] in item[1:-1]:
                return None
        elif "'" in item or '"' in item:
            return None
    keep = [i for i, segment in enumerate(segments) if not names_ref(segment)]
    dropped = len(segments) - len(keep)
    if not dropped:
        return value, 0, len(segments)
    if not keep:
        return "", dropped, 0
    kept = [segments[i] for i in keep]
    # Whatever is first or last now inherits the spacing the list had
    # just inside its brackets.
    if keep[0] != 0:
        first = segments[0]
        kept[0] = first[: len(first) - len(first.lstrip())] + kept[0].lstrip()
    if keep[-1] != len(segments) - 1:
        last = segments[-1]
        kept[-1] = kept[-1].rstrip() + last[len(last.rstrip()) :]
    return f"{lead}[{','.join(kept)}]", dropped, len(kept)


def _drop_yaml_read_entry(text: str, refs: set[str]) -> tuple[str, bool, str | None]:
    """Remove the entries of a top-level ``read:`` key that name ``refs``.

    Line-based so everything else in the file -- comments, blank lines,
    ordering, quoting, each line's own ending -- comes back byte for
    byte. Handles::

        read:
          - /home/me/.deepctl/skills/deepctl-conventions.md
        read: /home/me/.deepctl/skills/deepctl-conventions.md
        read: [a.md, /home/me/.deepctl/skills/deepctl-conventions.md]  # mine

    When the last entry goes, the ``read:`` line goes with it rather
    than being left as an empty key; a comment written on that line
    stays, on a line of its own.

    Returns the new text, whether anything changed, and a reason when
    the file names a ref in a ``read:`` list this cannot edit safely.
    """
    lines = text.splitlines(keepends=True)
    expanded = {os.path.expanduser(r) for r in refs} | refs

    def names_ref(raw: str) -> bool:
        value = _yaml_scalar(raw)
        return value in expanded or os.path.expanduser(value) in expanded

    def body(line: str) -> str:
        return line.rstrip("\r\n")

    key_at: int | None = None
    for i, line in enumerate(lines):
        if line.startswith("read:"):
            key_at = i
            break
    if key_at is None:
        return text, False, None

    key_line = lines[key_at]
    ending = key_line[len(body(key_line)) :]
    value, comment = _split_yaml_comment(body(key_line)[len("read:") :])
    rest = value.strip()
    out = list(lines)

    def drop_key() -> None:
        if comment.strip():
            out[key_at] = comment.strip() + ending
        else:
            del out[key_at]

    if rest:
        if rest.startswith("["):
            edited = _drop_flow_entries(value, names_ref)
            if edited is None:
                if any(ref in text for ref in expanded):
                    return text, False, "has a read: list deepctl could not edit safely"
                return text, False, None
            new_value, dropped, left = edited
            if not dropped:
                return text, False, None
            if left:
                out[key_at] = f"read:{new_value}{comment}{ending}"
            else:
                drop_key()
            return "".join(out), True, None
        if names_ref(rest):
            drop_key()
            return "".join(out), True, None
        return text, False, None

    # A block list: items (and comments or blanks between them) until the
    # next line that is neither.
    drop: list[int] = []
    item_count = 0
    j = key_at + 1
    while j < len(lines):
        stripped = body(lines[j]).strip()
        if not stripped or stripped.startswith("#"):
            j += 1
            continue
        if not (stripped.startswith("- ") or stripped == "-"):
            break
        item_count += 1
        if names_ref(stripped[1:]):
            drop.append(j)
        j += 1
    if not drop:
        return text, False, None
    # Items sit below the key, so deleting them first leaves key_at valid.
    for i in sorted(drop, reverse=True):
        del out[i]
    if len(drop) == item_count:
        drop_key()
    return "".join(out), True, None


